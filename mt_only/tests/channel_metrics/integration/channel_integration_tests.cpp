struct Decoded {meshtastic_Data data{};meshtastic_Telemetry telemetry{};};
static Decoded decode(const uint8_t *wire,size_t n) {
  Decoded d;auto in=pb_istream_from_buffer(wire,n);
  assert(pb_decode(&in,meshtastic_Data_fields,&d.data)&&!in.bytes_left);
  auto payload=pb_istream_from_buffer(d.data.payload.bytes,d.data.payload.size);
  assert(pb_decode(&payload,meshtastic_Telemetry_fields,&d.telemetry)&&!payload.bytes_left);
  assert(d.data.portnum==meshtastic_PortNum_TELEMETRY_APP&&d.data.request_id==17&&d.data.has_bitfield&&d.data.bitfield==0);
  assert(d.telemetry.which_variant==meshtastic_Telemetry_device_metrics_tag);
  return d;
}
static void encoderTests() {
  const auto max=std::numeric_limits<float>::max();
  const auto inf=std::numeric_limits<float>::infinity();
  const auto nan=std::numeric_limits<float>::quiet_NaN();
  for(float channel:{-0.0f,0.0f,std::numeric_limits<float>::denorm_min(),std::numeric_limits<float>::min(),0.125f,1.0f/6.0f,50.0f,100.0f}) {
    uint8_t wire[512];size_t n;
    assert(mt::TelemetryQuery::uptimeResponse(123,17,zt::Observed<float>{0.25f},zt::Observed<float>{channel},wire,sizeof(wire),n));
    auto decoded=decode(wire,n);const auto &m=decoded.telemetry.variant.device_metrics;
    assert(m.has_channel_utilization&&!memcmp(&m.channel_utilization,&channel,sizeof(channel)));
    assert(m.has_air_util_tx&&m.air_util_tx==0.25f&&m.has_uptime_seconds&&m.uptime_seconds==123);
    assert(!m.has_battery_level&&!m.has_voltage);
  }
  group("actual nanopb wire preserves present channel zeros and valid fractional float values");
  for(auto channel:{zt::Observed<float>{},zt::Observed<float>{nan},zt::Observed<float>{inf},zt::Observed<float>{-inf},zt::Observed<float>{-1.0f},zt::Observed<float>{100.01f},zt::Observed<float>{max}}) {
    uint8_t wire[512];size_t n;
    assert(mt::TelemetryQuery::uptimeResponse(UINT32_MAX,17,zt::Observed<float>{0.125f},channel,wire,sizeof(wire),n));
    const auto decoded=decode(wire,n);const auto &m=decoded.telemetry.variant.device_metrics;
    assert(!m.has_channel_utilization&&m.has_air_util_tx&&m.air_util_tx==0.125f);
    assert(m.has_uptime_seconds&&m.uptime_seconds==UINT32_MAX);
  }
  group("absent, nonfinite and outside range channel values omit independently of airtime and uptime");
  for(auto air:{zt::Observed<float>{},zt::Observed<float>{nan},zt::Observed<float>{inf},zt::Observed<float>{-inf},zt::Observed<float>{-1.0f},zt::Observed<float>{100.01f}}) {
    uint8_t wire[512];size_t n;
    assert(mt::TelemetryQuery::uptimeResponse(0,17,air,zt::Observed<float>{0.0f},wire,sizeof(wire),n));
    const auto decoded=decode(wire,n);const auto &m=decoded.telemetry.variant.device_metrics;
    assert(m.has_channel_utilization&&m.channel_utilization==0&& !m.has_air_util_tx&&m.has_uptime_seconds&&m.uptime_seconds==0);
  }
  group("invalid or absent airtime never removes valid channel zero or uptime zero");
  for(auto air:{zt::Observed<float>{},zt::Observed<float>{0.0f},zt::Observed<float>{0.125f},zt::Observed<float>{100.0f}}) {
    uint8_t oldWire[512],newWire[512];size_t oldN=0,newN=0;
    assert(mt::TelemetryQuery::uptimeResponse(222,17,air,oldWire,sizeof(oldWire),oldN));
    assert(mt::TelemetryQuery::uptimeResponse(222,17,air,{},newWire,sizeof(newWire),newN));
    assert(oldN==newN&&!memcmp(oldWire,newWire,oldN));
  }
  group("old overload delegates with channel absent and emits identical bytes");
  {
    uint8_t wire[512];size_t n=99;
    assert(!mt::TelemetryQuery::uptimeResponse(0,0,{},zt::Observed<float>{1},wire,sizeof(wire),n)&&n==0);
    n=99;assert(!mt::TelemetryQuery::uptimeResponse(0,17,{},zt::Observed<float>{1},wire,0,n)&&n==0);
    group("invalid request and insufficient output capacity fail without reported bytes");
  }
}
