static std::string hex(const uint8_t *bytes,size_t n) {
  const char digits[]="0123456789abcdef";std::string out;
  for(size_t i=0;i<n;++i){out+=digits[bytes[i]>>4];out+=digits[bytes[i]&15];}
  return out;
}
