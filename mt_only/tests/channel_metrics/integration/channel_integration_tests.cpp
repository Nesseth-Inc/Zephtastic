static void present(zt::Observed<float> value,uint32_t milliseconds) {
  assert(value.has_value());
  const float expected=float(milliseconds)/float(60000)*100;
  assert(*value==expected);
}
static void absent(zt::Observed<float> value){assert(!value.has_value());}
struct Drain {
  unsigned calls=0;bool fail=false;uint32_t credit=0;
  static void call(mt::ChannelMeter &meter,void *ctx) {
    auto &d=*static_cast<Drain *>(ctx);++d.calls;
    if(d.fail){d.fail=false;meter.uncertain();}
    if(d.credit){const auto value=d.credit;d.credit=0;meter.observeRx(value,true);}
  }
};
