#!/usr/bin/env python3
"""Encode the T096's stock 16x16 glyphs as row deltas with a shared byte-pair dictionary."""
from collections import Counter
from pathlib import Path
import argparse
import re


def encode(source):
    section = source.read_text().split("uint8_t bitmaps[][32]={", 1)[1].split("};", 1)[0]
    glyphs = [bytes.fromhex("".join(re.findall(r"0x([0-9a-fA-F]{2})", row)))
              for row in section.splitlines() if "0x" in row]
    if not glyphs or any(len(row) != 32 for row in glyphs):
        raise ValueError("expected 32 bytes per XBM glyph")
    deltas = [bytes(value ^ (row[i - 2] if i >= 2 else 0) for i, value in enumerate(row))
              for row in glyphs]
    alphabet = [value for value, _ in Counter(b"".join(deltas)).most_common(128)]
    index = {value: i for i, value in enumerate(alphabet)}
    escape = len(alphabet)
    # Rare bytes stay outside the pair alphabet until the final encoding pass.
    rows = [[index.get(byte, 256 + byte) for byte in row] for row in deltas]
    pairs = []
    depths = [0] * (escape + 1)
    for code in range(escape + 1, 256):
        counts = Counter((a, b) for row in rows for a, b in zip(row, row[1:]) if max(a, b) < 256)
        if not counts:
            break
        pair, count = counts.most_common(1)[0]
        if count < 3:
            break
        pairs.extend(pair)
        depths.append(1 + max(depths[pair[0]], depths[pair[1]]))
        for j, row in enumerate(rows):
            packed = []
            i = 0
            while i < len(row):
                if tuple(row[i:i+2]) == pair:
                    packed.append(code)
                    i += 2
                else:
                    packed.append(row[i])
                    i += 1
            rows[j] = packed
    offsets, data = [], []
    for row in rows:
        offsets.append(len(data))
        for value in row:
            data.extend((escape, value - 256) if value >= 256 else (value,))
    assert len(data) < 65536 and max(depths) <= 8

    def array(name, values, ctype="uint8_t"):
        lines = [", ".join(map(str, values[n:n+16])) for n in range(0, len(values), 16)]
        return f"inline constexpr {ctype} {name}[]={{\n    " + ",\n    ".join(lines) + "\n};"

    return "\n".join(["// Generated by pack-emotes.py from the pinned XBM glyphs.",
                      array("glyphAlphabet", alphabet), array("glyphPairs", pairs),
                      array("glyphOffsets", offsets, "uint16_t"), array("glyphData", data), ""])


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    args.output.write_text(encode(args.source))
